inline int Count(int page, int retailCount = 0) {
    if (page < 0 || page >= kPageCount) return 0;
    // The retail label buffer is 6 x 256 x 16 bytes (ARM64 2.11).
    // Zero, partial initialization, or missing symbols must not hide missions.
    const int knownCount = kPages[page].count;
    if (page == kDirectPage) return knownCount;
    return retailCount >= knownCount && retailCount <= 256
        ? retailCount : knownCount;
}

inline const char* Name(int page, int number) {
    if (page < 0 || page >= kPageCount || number < 0 ||
        number >= kPages[page].count) return "UNNAMED RETAIL ENTRY";
    return kPages[page].names[number];
}

